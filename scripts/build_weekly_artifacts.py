#!/usr/bin/env python3
"""Build the cron #6 weekly artifacts.

Outputs (all under /workspace/daily-screens/<date>/):
  weekly-ipo.md
  weekly-high-short-float.md
  peoplewish-backlog.md          <- cumulative backlog (prior run + newly tagged)
  peoplewish-backlog-run-full.json

Also maintains the long-lived canonical backlog at
/workspace/pattern-study/peoplewish-1000pct-backlog.md
"""
import json
import os
import re
import shutil
import sys

DATE = sys.argv[1] if len(sys.argv) > 1 else "2026-10-24"
SHIBUI_LATEST = sys.argv[2] if len(sys.argv) > 2 else "2026-10-23"
SCRATCH = "/workspace/.scratch"
OUT_DIR = f"/workspace/daily-screens/{DATE}"
CANON_DIR = "/workspace/pattern-study"
os.makedirs(OUT_DIR, exist_ok=True)
os.makedirs(CANON_DIR, exist_ok=True)

ipo_rows = json.load(open(f"{SCRATCH}/ipo.json"))
hsf_rows = json.load(open(f"{SCRATCH}/hsf.json"))
full_rows = json.load(open(f"{SCRATCH}/pattern_full.json"))
enriched = json.load(open(f"{SCRATCH}/pattern_enriched.json"))

# ---------------------------------------------------------------- tag rules
def tag_shape(r):
    tags = []
    cr = r.get("contraction_ratio") or 0
    close = r.get("current_close") or 0
    high_60d = r.get("high_60d") or 0
    ytd_low = r.get("ytd_low") or 0
    last_day = r.get("last_day_change_pct") or 0
    if close and high_60d:
        prox = close / high_60d
        if prox >= 0.95:
            tags.append("breakout")
        if prox >= 0.85 and cr < 0.85:
            tags.append("coil")
    if cr and cr < 0.65:
        tags.append("VCP")
    if ytd_low and close and close > 1.50 * ytd_low:
        tags.append("EP")
    if last_day and abs(last_day) >= 5:
        tags.append("big_day")
    return tags

for r in enriched:
    r["shape_tags"] = tag_shape(r)

# Dedupe enriched by ticker, keep first
seen, uniq = set(), []
for r in enriched:
    if r["ticker"] not in seen:
        seen.add(r["ticker"])
        uniq.append(r)
enriched = uniq

# ------------------------------------------------- load prior backlog history
prior_files = sorted(
    p for p in os.listdir("/workspace/daily-screens")
    if os.path.isdir(f"/workspace/daily-screens/{p}") and p < DATE
) if os.path.isdir("/workspace/daily-screens") else []

PRIOR_RE = re.compile(
    r"^\| \d+ \| ([A-Z0-9.\-]+) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$"
)

prior_entries = []   # list of dicts
prior_meta = []      # list of (run_date, count)
prior_dir = None
for d in reversed(prior_files):
    p = f"/workspace/daily-screens/{d}/peoplewish-backlog.md"
    if not os.path.exists(p):
        continue
    prior_dir = d
    txt = open(p).read()
    m = re.search(r"## New entries \((\d{4}-\d{2}-\d{2}) run\)", txt)
    run_date = m.group(1) if m else d
    for line in txt.splitlines():
        mm = PRIOR_RE.match(line.strip())
        if mm:
            g = mm.groups()
            prior_entries.append({
                "ticker": g[0], "name": g[1], "exchange": g[2], "sector": g[3],
                "current": g[4], "low10": g[5], "peak": g[6], "gain": g[7],
                "high60": g[8], "contraction": g[9], "ytd_low": g[10],
                "last_day": g[11], "tags": g[12],
                "first_tagged": run_date, "is_new": False,            })
    prior_meta.append((run_date, len(prior_entries)))
    break

prior_tickers = {e["ticker"] for e in prior_entries}
prior_types = {}
if os.path.exists(f"{SCRATCH}/prior_types.json"):
    prior_types = json.load(open(f"{SCRATCH}/prior_types.json"))

# Security-type policy: the peoplewish 1000%-in-10y study is an EQUITY study
# (chart shapes: coil / VCP / breakout / EP). Leveraged ETNs and ETFs inflate
# 10y returns mechanically and have no chart worth studying, so newly-tagged
# names are restricted to Common Stock (shibui schema rule: "Always filter
# g.type = 'Common Stock' unless the user specifically asks for REITs, ADRs,
# ETFs, etc."). Legacy rows are kept but flagged, not silently dropped.
new_rows_all = [r for r in enriched if r["ticker"] not in prior_tickers]
new_rows = [r for r in new_rows_all if (r.get("sec_type") or "Common Stock") == "Common Stock"]
excluded = [r for r in new_rows_all if (r.get("sec_type") or "Common Stock") != "Common Stock"]
seen_rows = [r for r in enriched if r["ticker"] in prior_tickers]

# ------------------------------------------------------- weekly-ipo.md
ipo_md = f"""# Weekly IPO Refresh — {DATE}

_Generated by cron #6 stock-screener-pattern-study-backlog. Source: shibui-finance MCP (`shibui.general_info` + `shibui.valuation`)._

**Universe:** Common Stock IPOs listed in the last 365 days with market_cap > $1B (or no valuation row yet). **Latest available shibui date:** {SHIBUI_LATEST} (T+1 lag vs cron date {DATE}).

**Count:** {len(ipo_rows)} tickers (cap 50), newest first.

| # | Ticker | Name | Exchange | IPO Date | MCap ($B) | Sector | Industry |
|---|---|---|---|---|---|---|---|
"""
for i, r in enumerate(ipo_rows, 1):
    name = (r.get("name") or "—")[:50]
    mcap = r.get("market_cap_bil")
    mcap_s = f"{mcap:.2f}" if mcap is not None else "—"
    ipo_md += (f"| {i} | {r['ticker']} | {name} | {r['exchange']} | {r['ipo_date']} | {mcap_s} | "
               f"{r.get('gics_sector') or '—'} | {r.get('gics_industry') or '—'} |\n")

ipo_md += f"""
## Notes
- `MCap = —` means no `shibui.valuation` row in the last 7 trading days (recent IPO, SPAC, or foreign-domicile issuer not yet stamped). These pass the $1B floor by default rather than being excluded.
- Filter N reference: `ipodate_l5y, cap_midover` (Finviz). shibui has no `shibui.reference` table — `ipo_date` lives on `shibui.general_info`; market cap comes from the latest `shibui.valuation` snapshot. This run tightens the window to 365 days (per filter N SQL) instead of Finviz's 5y.
- `type = 'Common Stock'` filter applied — ETFs, REITs, ADRs and units are excluded.
- `_source=mcp` (shibui primary path; Finviz fallback not triggered).
"""

with open(f"{OUT_DIR}/weekly-ipo.md", "w") as f:
    f.write(ipo_md)

# -------------------------------------------- weekly-high-short-float.md
hsf_md = f"""# Weekly High-Short-Float Refresh — {DATE}

_Generated by cron #6 stock-screener-pattern-study-backlog. Source: shibui-finance MCP (`shibui.ownership_stats` + `shibui.valuation` + `shibui.stock_quotes`)._

**Universe:** Common Stock with `short_percent_float > 20%`. **Latest available shibui date:** {SHIBUI_LATEST} (T+1 lag vs cron date {DATE}).

**Count:** {len(hsf_rows)} tickers (cap 30, sorted by `short_pct_float` desc).

| # | Ticker | Name | Exchange | Short %Float | MCap ($B) | Close | 30d ADVol ($M) | Sector |
|---|---|---|---|---|---|---|---|---|
"""
for i, r in enumerate(hsf_rows, 1):
    name = (r.get("name") or "—")[:45]
    short_pct = r.get("short_pct_float") or 0
    mcap = r.get("market_cap_bil")
    mcap_s = f"{mcap:.2f}" if mcap is not None else "—"
    close = r.get("close_price")
    close_s = f"${close:.2f}" if close is not None else "—"
    adv = r.get("adv_dollar_mil")
    adv_s = f"{adv:.1f}" if adv is not None else "—"
    hsf_md += (f"| {i} | {r['ticker']} | {name} | {r['exchange']} | {short_pct:.1f}% | {mcap_s} | "
               f"{close_s} | {adv_s} | {r.get('gics_sector') or '—'} |\n")

hsf_md += f"""
## Notes
- `short_percent_float` is a **fraction** in shibui (`0.20` = 20%); values > 100% occur (OWLS 443.9%) where disclosed short interest exceeds float, typical of recent IPOs/SPACs with synthetic longs — treat those as un-actionable noise, not squeeze fuel.
- 30d ADVol = `AVG(close * volume)` over the last 30 trading days. `—` = insufficient history.
- Filter O reference: `sh_short_o20, sh_avgvol_o500k` (Finviz). shibui has no `days_to_cover` column, so that field is dropped per the filter spec's own instruction. The Finviz 500k-share floor is approximated by leaving the 30d ADVol column visible rather than pre-pruning, so micro-cap squeezes stay in the table for review.
- Squeeze-relevant tier: `short > 50%` AND ADVol > $20M. Everything below $5M ADVol is untradeable for size.
- `_source=mcp` (shibui primary path; Finviz fallback not triggered).
"""

with open(f"{OUT_DIR}/weekly-high-short-float.md", "w") as f:
    f.write(hsf_md)

# ------------------------------------------------- peoplewish backlog (cumulative)
backlog_md = f"""# peoplewish 1000%-in-10-years — Pattern-Study Backlog

_Long-lived log of US equities that have compounded 1000%+ from their 10-year low
to the most recent close. Maintained by cron #6 stock-screener-pattern-study-backlog
(Saturday weekly). Newly-discovered names are appended each Saturday._

## Methodology

- **Universe:** all symbols in shibui.stock_quotes with at least 1,260 trading days in the
  trailing 10-year window (≥ 5y of data — filters out recent IPOs / SPAC mergers that would
  not have a real 10-yr baseline).
- **Trigger:** `(current_close / 10y_min_close) - 1 >= 10.0` (i.e., 1000%+ from trough).
- **Min close filter:** `min_close_10y >= $0.50` (avoids micro-cap noise that hit 1000% off a sub-penny base).
- **Sort:** current gain from 10y low, descending. Scan cap 200 rows per run; top 100 get shape tags.
- **Security type:** newly-tagged names are restricted to `type = 'Common Stock'`. Leveraged ETNs and
  ETFs inflate a 10-year return mechanically and have no chart shape worth studying, so they are
  excluded from the tag list (the raw scan still records them in the run JSON).
- **Chart-shape tags** (computed on the most recent 60d / 10d window of stock_quotes):
  - `coil` — close within 15% of 60d high AND contraction_ratio (10d range / 60d range) < 0.85
  - `VCP` — Volatility Contraction Pattern: contraction_ratio < 0.65 (10d range < 65% of 60d range)
  - `breakout` — close within 5% of 60d high (close / high_60d ≥ 0.95)
  - `EP` — Extended Play: current close > 50% above YTD low (already in a strong uptrend)
  - `big_day` — most recent trading day moved > 5% (catalyst signal)

## Run manifest

- **Run date (ET):** {DATE} (Saturday 10:00 ET cron)
- **Latest shibui data:** {SHIBUI_LATEST} (T+1 lag vs cron date)
- **Source:** shibui MCP (streamable-http `https://mcp.shibui.finance/mcp`), `stock_data_query`
- **Scan:** {len(full_rows)} rows returned by the 10y scan; {len(enriched)} shape-tagged
- **Newly tagged this run:** {len(new_rows)} common stocks (already-known names carried forward: {len(seen_rows)}; non-equity rows excluded: {len(excluded)})
- **Cumulative backlog size:** {len(prior_entries) + len(new_rows)}
- **Prior backlog source:** {f'daily-screens/{prior_dir}/peoplewish-backlog.md' if prior_dir else 'none (first run)'}
- **Source tag:** `_source=mcp`

## Newly tagged entries ({DATE} run)

| # | Ticker | Name | Type | Exchange | Sector | Current | 10y Low | Peak Gain | Gain | 60d High | Contraction | YTD Low | Last Day | Tags |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
"""
for i, r in enumerate(new_rows, 1):
    name = (r.get("name") or "—")[:45]
    tags = ", ".join(r["shape_tags"]) if r["shape_tags"] else "—"
    backlog_md += (
        f"| {i} | {r['ticker']} | {name} | {r.get('sec_type') or '—'} | {r['exchange']} | {r.get('gics_sector') or '—'} | "
        f"${r.get('current_close') or 0:.2f} | ${r.get('min_close_10y') or 0:.2f} | "
        f"{r.get('peak_gain_pct') or 0:.0f}% | {r.get('gain_pct') or 0:.0f}% | "
        f"${r.get('high_60d') or 0:.2f} | {r.get('contraction_ratio') or 0:.2f} | "
        f"${r.get('ytd_low') or 0:.2f} | {(r.get('last_day_change_pct') or 0):+.2f}% | {tags} |\n"
    )

if excluded:
    backlog_md += f"""
### Excluded from tagging (non-Common-Stock, {len(excluded)})

| Ticker | Name | Type | Gain | 10y Low | Why excluded |
|---|---|---|---|---|---|
"""
    for r in excluded:
        why = ("leveraged/fund vehicle — 10y return is mechanical, not stock-picking"
               if r.get("sec_type") == "ETF" else
               "foreign-domicile issuer — ADR, not a US-listed common stock")
        backlog_md += (
            f"| {r['ticker']} | {(r.get('name') or '—')[:45]} | {r.get('sec_type')} | "
            f"{r.get('gain_pct') or 0:.0f}% | ${r.get('min_close_10y') or 0:.2f} | {why} |\n"
        )

if prior_entries:
    legacy_non_eq = [e for e in prior_entries
                     if prior_types.get(e["ticker"], "Common Stock") != "Common Stock"]
    backlog_md += f"""
## Carried forward (first tagged on or before {DATE})

| Ticker | Name | Type | Exchange | Sector | Current | 10y Low | Peak Gain | Gain | 60d High | Contraction | YTD Low | Last Day | Tags | First Tagged |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
"""
    for e in prior_entries:
        etype = prior_types.get(e["ticker"], "Common Stock")
        flag = " ⚠" if etype != "Common Stock" else ""
        backlog_md += (
            f"| {e['ticker']}{flag} | {e['name']} | {etype} | {e['exchange']} | {e['sector']} | {e['current']} | "
            f"{e['low10']} | {e['peak']} | {e['gain']} | {e['high60']} | {e['contraction']} | "
            f"{e['ytd_low']} | {e['last_day']} | {e['tags']} | {e['first_tagged']} |\n"
        )
    if legacy_non_eq:
        backlog_md += f"""
⚠ = tagged before the Common-Stock filter was applied. {len(legacy_non_eq)} legacy rows are ETFs / ADRs / a REIT and are retained for ledger continuity but should be ignored for stock-pattern research: {', '.join(e['ticker'] for e in legacy_non_eq)}.
"""

backlog_md += f"""
## Notes
- Rows in **Carried forward** are frozen at the values they carried when first tagged — they are a discovery ledger, not a live quote sheet. Re-scan for live values via the daily sweep.
- {len(new_rows)} of the {len(enriched)} shape-tagged names were new common stocks this week; {len(seen_rows)} were already in the backlog and are not duplicated; {len(excluded)} were excluded for non-equity type.
- Full 200-row scan (including untagged ranks {len(enriched)+1}-{len(full_rows)}) is preserved in `peoplewish-backlog-run-full.json` in this directory.
- Cross-reference: the peoplewish screener (filter G) uses 14d velocity as primary sort; this backlog is the multi-year analogue.
- Market note: the 10y-trough basis means the 1000% set is sensitive to drawdown. A name dropping 50% off its high can fall out of the top ranks without ever leaving the backlog.
"""

with open(f"{OUT_DIR}/peoplewish-backlog.md", "w") as f:
    f.write(backlog_md)

# Canonical long-lived backlog
with open(f"{CANON_DIR}/peoplewish-1000pct-backlog.md", "w") as f:
    f.write(backlog_md)

with open(f"{OUT_DIR}/peoplewish-backlog-run-full.json", "w") as f:
    json.dump({
        "run_date": DATE,
        "source": "shibui MCP (streamable-http at https://mcp.shibui.finance/mcp)",
        "shibui_latest_date": SHIBUI_LATEST,
        "scan_window": "10y",
        "filter": "(current_close / 10y_min_close) - 1 >= 10.0 AND 10y_min >= 0.50 AND rows_10y >= 1260",
        "scan_count": len(full_rows),
        "tagged_count": len(enriched),
        "newly_tagged": [r["ticker"] for r in new_rows],
        "already_known": [r["ticker"] for r in seen_rows],
        "cumulative_backlog_size": len(prior_entries) + len(new_rows),
        "rows_full": full_rows,
    }, f, indent=2)

print("FILES:")
for f_ in ["weekly-ipo.md", "weekly-high-short-float.md", "peoplewish-backlog.md",
           "peoplewish-backlog-run-full.json"]:
    p = f"{OUT_DIR}/{f_}"
    print(f"  {p} ({os.path.getsize(p)} bytes)")
print(f"  {CANON_DIR}/peoplewish-1000pct-backlog.md "
      f"({os.path.getsize(CANON_DIR + '/peoplewish-1000pct-backlog.md')} bytes)")
print()
print(f"IPO={len(ipo_rows)} HSF={len(hsf_rows)} scan={len(full_rows)} "
      f"tagged={len(enriched)} new={len(new_rows)} carried={len(prior_entries)} "
      f"cumulative={len(prior_entries)+len(new_rows)}")
