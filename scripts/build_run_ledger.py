WEEKDAY = {"Mon": 0, "Tue": 1, "Wed": 2, "Thu": 3, "Fri": 4, "Sat": 5, "Sun": 6}


def trading_sessions():
    """The sessions `us-eod/` records. This repo's own calendar of open days."""
    out = []
    root = os.path.join(J.REPO, "us-eod")
    for name in sorted(os.listdir(root)):
        if name.endswith(".csv") and re.match(r"^\d{4}-\d{2}-\d{2}$", name[:-4]):
            out.append(name[:-4])
    return out


def scheduled_days(routine, days, sessions):
    """The dates this routine was expected to fire, given its weekday rule.

    A weekday routine is expected on a TRADING day, not on every weekday: the
    `us-eod/` file set is this repo's own record of which days the US market
    was open. A routine that fires on a non-trading day is a real observation,
    not an error, so those are counted separately as UNSCHEDULED.
    """
    if days == "Mon-Fri":
        return list(sessions)
    if days == "every day":
        return []
    target = WEEKDAY.get(days)
    if target is None:
        return []
    out = []
    for d in sessions:
        try:
            if datetime.date.fromisoformat(d).weekday() == target:
                out.append(d)
        except ValueError:
            continue
    return out


def artifacts_for(pattern):
    """Every artifact matching a glob, with the date it belongs to.

    A WEEKLY artifact is keyed by the ISO week it names (`2026-W44`), not by a
    date. Its routine fires on one day a week, so the ledger compares it
    against the sessions in that week rather than against a single date.
    """
    import glob
    out = []
    for path in glob.glob(os.path.join(J.REPO, pattern)):
        rel = os.path.relpath(path, J.REPO).replace(os.sep, "/")
        iso_week = None
        m = re.search(r"(20\d{2})-W(\d{2})", rel)
        if m:
            iso_week = "%s-W%s" % (m.group(1), m.group(2))
        dates = re.findall(r"(20\d{2}-\d{2}-\d{2})", rel)
        date = dates[0] if dates else None
        out.append({
            "path": rel,
            "date": date,
            "iso_week": iso_week,
            "bytes": os.path.getsize(path),
            "mtime": datetime.datetime.fromtimestamp(os.path.getmtime(path)).strftime("%Y-%m-%d"),
        })
    return out


def week_sessions(iso_week, sessions):
    """The trading sessions inside one ISO week."""
    year, wk = iso_week.split("-W")
    start = datetime.date.fromisocalendar(int(year), int(wk), 1)
    out = []
    for d in sessions:
        try:
            if datetime.date.fromisoformat(d).isocalendar()[:2] == (int(year), int(wk)):
                out.append(d)
        except ValueError:
            continue
    return out


def count_names(path):
    """How many names an artifact published, where it says."""
    if path.endswith(".csv"):
        rows = J.read_csv_rows(path)
        return len(rows)
    try:
        text = open(path, encoding="utf-8", errors="replace").read()
    except OSError:
        return None
    m = re.search(r"^\|?\s*(?:Candidates|Names|names?)\s*[:|]\s*\*\*(\d+)", text, re.M | re.I)
    if m:
        return int(m.group(1))
    return None


def build():
    sessions = trading_sessions()
    first_session = sessions[0] if sessions else None
    last_session = sessions[-1] if sessions else None
    rows = []
    for routine, fire, days, pattern, cadence in SCHEDULE:
        arts = artifacts_for(pattern)
        expected = set(scheduled_days(routine, days, sessions))
        for a in arts:
            if a["iso_week"]:
                # A weekly artifact covers the sessions of its week. It counts
                # as published if any session in that week was a session its
                # routine was scheduled for.
                in_week = week_sessions(a["iso_week"], sessions)
                scheduled_in_week = set(scheduled_days(routine, days, in_week))
                if scheduled_in_week:
                    state = "published"
                elif in_week:
                    state = "published_off_schedule"
                else:
                    state = "published_after_calendar"
                rows.append({
                    "date": a["iso_week"],
                    "routine": routine,
                    "fire_et": fire,
                    "schedule": days,
                    "expected": bool(scheduled_in_week),
                    "state": state,
                    "artifact": a["path"],
                    "bytes": a["bytes"],
                    "names": count_names(os.path.join(J.REPO, a["path"])),
                })
                continue
            date = a["date"]
            if not date:
                continue
            if date in expected:
                state = "published"
            elif first_session and date < first_session:
                # Before the trading calendar this repo records. The routine
                # firing is not off-schedule; the repo simply cannot say.
                state = "published_before_calendar"
            elif last_session and date > last_session:
                # After the last session us-eod/ records. The routine fired on a
                # day this repo has no settled-session record for, so the
                # schedule cannot be evaluated against it.
                state = "published_after_calendar"
            else:
                state = "published_off_schedule"
            rows.append({
                "date": date,
                "routine": routine,
                "fire_et": fire,
                "schedule": days,
                "expected": date in expected,
                "state": state,
                "artifact": a["path"],
                "bytes": a["bytes"],
                "names": count_names(os.path.join(J.REPO, a["path"])),
            })
        # expected but absent
        for date in sorted(expected):
            present = any(r["date"] == date and r["routine"] == routine for r in rows)
            if not present:
                rows.append({
                    "date": date,
                    "routine": routine,
                    "fire_et": fire,
                    "schedule": days,
                    "expected": True,
                    "state": "missing",
                    "artifact": None,
                    "bytes": None,
                    "names": None,
                })

    # The earliest sessions are not misses: the fleet was still starting up, so
    # a routine that published nothing then was not yet running. A routine's
    # FIRST publication in this repo sets the point from which its absence is
    # meaningful, and a gap before it is not a gap.
    for routine in {r["routine"] for r in rows}:
        rs = [r for r in rows if r["routine"] == routine]
        published = sorted(r["date"] for r in rs if r["state"].startswith("published"))
        if not published:
            continue
        onset = published[0]
        for r in rs:
            if r["state"] == "missing" and r["date"] < onset:
                r["state"] = "before_onset"
    return rows, sessions


def render(rows, sessions):
    lines = []
    lines.append("# Run ledger — which routine published what, and when")
    lines.append("")
    lines.append(J.provenance(
        "derived read of the published artifacts, against the schedule in the "
        "migration repo's ROSTER.md (read 2026-11-09); no source file is modified",
        "%d artifact-date rows across %d routines and %d trading sessions"
        % (len(rows), len({r["routine"] for r in rows}), len(sessions)),
        "read-only",
    ))
    lines.append("")
    lines.append("> **Read this before the table.**")
    lines.append(">")
    lines.append("> 1. **A `missing` row is a fact about THIS REPO, not about the routine.**")
    lines.append(">    A routine can fire and fail to push, and a repo cannot tell those")
    lines.append(">    apart. The row says the artifact is not here; it does not say the")
    lines.append(">    routine did not run.")
    lines.append("> 2. **The schedule is the roster's, copied here.** A derived view should not")
    lines.append(">    depend on a file in another repo being present. When the roster")
    lines.append(">    changes, this constant changes with it.")
    lines.append("> 3. **A routine's first publication sets its onset.** A day before a")
    lines.append(">    routine had published anything here is not a miss - the fleet was still")
    lines.append(">    starting up. Those rows are counted apart.")
    lines.append("> 4. **A weekday routine is expected on a TRADING day.** The trading-day")
    lines.append(">    calendar is the one `us-eod/` itself records, so a holiday is not a miss.")
    lines.append("")

    published = [r for r in rows if r["state"] == "published"]
    missing = [r for r in rows if r["state"] == "missing"]
    off = [r for r in rows if r["state"] == "published_off_schedule"]
    before = [r for r in rows if r["state"] == "published_before_calendar"]
    after = [r for r in rows if r["state"] == "published_after_calendar"]
    onset = [r for r in rows if r["state"] == "before_onset"]

    lines.append("## Coverage")
    lines.append("")
    lines.append("| State | Rows |")
    lines.append("|---|---|")
    lines.append("| published, on schedule | %d |" % len(published))
    lines.append("| published, off schedule | %d |" % len(off))
    lines.append("| published, before the calendar this repo records | %d |" % len(before))
    lines.append("| published, after the calendar this repo records | %d |" % len(after))
    lines.append("| expected but not present in this repo | %d |" % len(missing))
    lines.append("| expected, before the routine had started publishing here | %d |" % len(onset))
    lines.append("| **total** | **%d** |" % len(rows))
    lines.append("")

    lines.append("## By routine")
    lines.append("")
    lines.append("| Routine | Fire | Schedule | Published | Missing | Off schedule | Last published here |")
    lines.append("|---|---|---|---|---|---|---|")
    by_routine = {}
    for r in rows:
        by_routine.setdefault(r["routine"], []).append(r)
    for routine, fire, days, _pattern, _cadence in SCHEDULE:
        rs = by_routine.get(routine, [])
        pub = [r for r in rs if r["state"] == "published"]
        mis = [r for r in rs if r["state"] == "missing"]
        offr = [r for r in rs if r["state"] == "published_off_schedule"]
        last = max((r["date"] for r in pub), default="—")
        lines.append("| %s | %s | %s | %d | %d | %d | %s |" % (
            routine, fire, days, len(pub), len(mis), len(offr), last))
    lines.append("")
    lines.append("**What this table means.** `Published` counts the artifact-date pairs this")
    lines.append("repo holds for that routine on a day its schedule covers. `Missing` counts the")
    lines.append("days it should have published and this repo does not hold. The gap between")
    lines.append("the two columns and the roster's own `Last delivered` column is the thing")
    lines.append("this artifact exists to show.")
    lines.append("")

    if off:
        lines.append("## Published off schedule")
        lines.append("")
        lines.append("| Date | Routine | Artifact |")
        lines.append("|---|---|---|")
        for r in sorted(off, key=lambda r: (r["date"], r["routine"])):
            lines.append("| %s | %s | `%s` |" % (r["date"], r["routine"], r["artifact"]))
        lines.append("")
        lines.append("An artifact on a day the schedule does not cover is not an error - a")
        lines.append("routine can be re-run manually, and a holiday can shift a fire. It is")
        lines.append("counted apart from the scheduled runs so the two are not confused.")
        lines.append("")

    if missing:
        lines.append("## Expected but not present here")
        lines.append("")
        lines.append("| Date | Routine | Fire |")
        lines.append("|---|---|---|")
        for r in sorted(missing, key=lambda r: (r["date"], r["routine"])):
            lines.append("| %s | %s | %s |" % (r["date"], r["routine"], r["fire_et"]))
        lines.append("")

    lines.append("## Every published artifact")
    lines.append("")
    lines.append("| Date | Routine | State | Artifact | Names |")
    lines.append("|---|---|---|---|---|")
    for r in sorted(rows, key=lambda r: (r["date"], r["routine"])):
        if r["state"] == "missing":
            continue
        lines.append("| %s | %s | %s | `%s` | %s |" % (
            r["date"], r["routine"], r["state"], r["artifact"],
            "—" if r["names"] is None else r["names"]))
    lines.append("")
    lines.append("## Method and caveats")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|---|---|")
    lines.append("| Trading-day calendar | the `us-eod/*.csv` file set |")
    lines.append("| Schedule | the migration repo's ROSTER.md, copied into this script |")
    lines.append("| Date of an artifact | the date in its path |")
    lines.append("| Names published | the row count of a CSV, or the count the artifact states |")
    lines.append("")
    return "\n".join(lines) + "\n"


CSV_COLS = ["date", "routine", "fire_et", "schedule", "expected", "state", "artifact", "bytes", "names"]


def render_csv(rows):
    out = [",".join(CSV_COLS)]
    for r in sorted(rows, key=lambda r: (r["date"], r["routine"])):
        vals = []
        for c in CSV_COLS:
            v = r.get(c)
            if v is None:
                v = ""
            s = str(v)
            if "," in s or '"' in s:
                s = '"%s"' % s.replace('"', '""')
            vals.append(s)
        out.append(",".join(vals))
    return "\n".join(out) + "\n"


def main(argv):
    check_only = "--check" in argv
    rows, sessions = build()
    if check_only:
        published = sum(1 for r in rows if r["state"] == "published")
        missing = sum(1 for r in rows if r["state"] == "missing")
        off = sum(1 for r in rows if r["state"] == "published_off_schedule")
        print("rows %d | published %d | missing %d | off-schedule %d | sessions %d"
              % (len(rows), published, missing, off, len(sessions)))
        return 0
    a = J.write_if_changed(os.path.join(J.REPO, OUT_ROOT, "run-ledger.md"), render(rows, sessions))
    b = J.write_if_changed(os.path.join(J.REPO, OUT_ROOT, "run-ledger.csv"), render_csv(rows))
    print("run-ledger.md %s · run-ledger.csv %s (%d rows)" % (a, b, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
