#!/usr/bin/env python3
"""A run ledger: which routine fired on which day, and what it published.

Why: the roster in the migration repo is a snapshot. It says earnings-reminder
last delivered 2026-11-04 and asia-pre-market 2026-11-05, but this repo holds
2026-11-09 artifacts for both. The roster is regenerated by a tool that reads
the live scheduler, and this repo - which holds the evidence - has no answer of
its own to "which routines fired on which day".

That question has three answers, and the repo currently answers none of them:
  - did a routine fire on a day it should have?
  - did it fire on a day it should not have (a weekend run, a holiday)?
  - what did it publish when it did?

This builds the answer from the artifacts themselves. The schedule comes from
the roster's own table - copied here as a constant, because a derived view
should not depend on a file in another repo being present - and the FIRED
answer comes from what is on disk.

Two states matter and are kept apart:
  - expected   - the routine's schedule says it should have fired
  - present    - an artifact for that date exists in this repo

A gap between them is a MISS, which is a fact about this repo and not
necessarily about the routine: a routine can fire and fail to push, and this
repo cannot tell those apart. The ledger says "not present here" rather than
"did not run", and names that limit in the artifact.

  python3 scripts/build_run_ledger.py
  python3 scripts/build_run_ledger.py --check
"""
