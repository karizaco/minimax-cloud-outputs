#!/usr/bin/env python3
"""Build the client-safe twin of every published narrative artifact.

Why: the Minimax Code desktop client renders a narrow subset of markdown —
bold, italics, and lists. The artifacts in this repo are written for GitHub,
where a wide table and an emoji band are exactly right, so the artifact is not
wrong. But the same text reaches a reader through the client, where those two
constructs are unavailable: a table arrives as raw pipe characters and a flag
glyph arrives as a tofu box or nothing at all.

This writes a second copy of each narrative artifact, rendered for the client.
It is a TWIN, not an edit: the original is untouched and remains the canonical
GitHub rendering. The twin drops nothing that can be said in a list, and where
a table row has more columns than a bullet can carry, it says how many were
left in the artifact rather than silently discarding them.

The narrative families only. This is not a copy of the whole repo: the CSVs,
the decision records, the index and the reference documents are read as files,
not as chat, and duplicating them would be noise.

  python3 scripts/build_client_safe.py
  python3 scripts/build_client_safe.py --check
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _joinlib as J  # noqa: E402
from check_reply_format import check  # noqa: E402
from render_client_safe import render  # noqa: E402

OUT_ROOT = os.path.join("derived", "client-safe")

# The families a reader opens as prose. Each entry is a glob relative to the
# repo root; the twin keeps the path under OUT_ROOT.
FAMILIES = (
    "daily-screens/*/daily-sweep.md",
    "daily-screens/*/breadth.md",
    "daily-screens/*/breadth-snapshot.md",
    "daily-briefs/*.md",
    "us-stocks-in-play/*.md",
    "ntrt/*.md",
    "earnings/*.md",
    "weekly/*.md",
    "cross-asset/*.md",
    "options-flow/*.md",
    "international-eod/*/summary.md",
    "macro-calendar/*.md",
    "asia-pre-market/*.md",
)


def source_files():
    out = []
    for pat in FAMILIES:
        out += glob.glob(os.path.join(J.REPO, pat))
    return sorted(set(out))


def banner(relative_source):
    """One line at the top of every twin, saying what it is and where it came from."""
    return ("<!-- Client-safe rendering of `%s`. The original artifact is canonical; "
            "this twin is generated by scripts/build_client_safe.py for a client "
            "that renders bold, italics and lists only. -->\n" % relative_source)


def main(argv):
    check_only = "--check" in argv
    files = source_files()
    if not files:
        print("no narrative artifacts found", file=sys.stderr)
        return 2

    written = 0
    total_findings = 0
    for path in files:
        rel = os.path.relpath(path, J.REPO).replace(os.sep, "/")
        text = open(path, encoding="utf-8").read()
        out_text = banner(rel) + render(text)
        fails = check(out_text, "reply")
        total_findings += len(fails)
        if check_only:
            if fails:
                print("%-58s %d finding(s)" % (rel[:58], len(fails)))
            continue
        dest = os.path.join(J.REPO, OUT_ROOT, rel)
        status = J.write_if_changed(dest, out_text)
        if status == "written":
            written += 1

    if check_only:
        print("%d file(s) checked, %d finding(s) remaining" % (len(files), total_findings))
        return 1 if total_findings else 0
    print("client-safe twins: %d written, %d file(s) total, %d finding(s) remaining"
          % (written, len(files), total_findings))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
